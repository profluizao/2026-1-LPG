'''
Faça um programa usando Linguagem Python, que receba dois números inteiros e ao final imprima
a soma deles.
'''
# Recebe dois números inteiros
num1 = int(input("Digite o primeiro número: "))
num2 = int(input("Digite o segundo número: "))
# Calcula a soma
soma = num1 + num2
# Imprime o resultado
print("A soma dos números é:", soma)
