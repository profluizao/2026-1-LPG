'''
Faça um programa usando Linguagem Python, que peça ao usuário que digite dois números e
mostre o produto deles.
'''
# Recebe dois números do usuário
num1 = float(input("Digite o primeiro número: "))
num2 = float(input("Digite o segundo número: "))
# Calcula o produto
produto = num1 * num2
# Mostra o resultado
print("O produto dos números é:", produto)
